"use client";

import { useEffect, useSyncExternalStore } from "react";

export const LANGS = [
  { code: "en", native: "English" },
  { code: "hi", native: "हिन्दी" },
  { code: "mr", native: "मराठी" },
] as const;
export type Lang = (typeof LANGS)[number]["code"];

/** BCP-47 tags for the browser's speech engines. */
export const SPEECH_LANG: Record<Lang, string> = { en: "en-IN", hi: "hi-IN", mr: "mr-IN" };

const KEY = "finpilot_lang";
const listeners = new Set<() => void>();

/** Whether the simple view is in effect (written by useSimpleMode); sent with chat requests. */
export function getSimpleNow(): boolean {
  try {
    return localStorage.getItem("finpilot_simple_now") === "1";
  } catch {
    return false;
  }
}

export function getLang(): Lang {
  try {
    const v = localStorage.getItem(KEY);
    return LANGS.some((l) => l.code === v) ? (v as Lang) : "en";
  } catch {
    return "en";
  }
}

export function setLang(code: Lang) {
  try {
    localStorage.setItem(KEY, code);
  } catch {}
  listeners.forEach((l) => l());
}

export function useLang(): Lang {
  const lang = useSyncExternalStore((cb) => (listeners.add(cb), () => void listeners.delete(cb)), getLang, () => "en" as Lang);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = "ltr";
  }, [lang]);
  return lang;
}

